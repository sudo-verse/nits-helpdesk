#!/usr/bin/env node
/**
 * Regenerates the subsetted Material Symbols Outlined font.
 *
 * Reads scripts/icon-names.txt (one icon name per line) and downloads a
 * variable woff2 containing only those glyphs, keeping all four axes
 * (opsz, wght, FILL, GRAD) so the design's `'FILL' 1` active-nav state works.
 *
 *   npm run fonts:icons
 *
 * Run this after adding an icon name, otherwise the new glyph renders as a
 * blank box (or as its literal ligature text).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const NAMES_FILE = resolve(root, "scripts/icon-names.txt");
const OUT_FILE = resolve(root, "src/assets/fonts/material-symbols-outlined.woff2");
const TYPES_FILE = resolve(root, "src/lib/icons.ts");

// Google Fonts rejects the request unless icon_names is byte-sorted and unique.
const names = [
  ...new Set(
    readFileSync(NAMES_FILE, "utf8")
      .split("\n")
      .map((l) => l.trim())
      .filter(Boolean),
  ),
].sort();

const unsorted = readFileSync(NAMES_FILE, "utf8")
  .split("\n")
  .map((l) => l.trim())
  .filter(Boolean);
if (unsorted.join(",") !== names.join(",")) {
  writeFileSync(NAMES_FILE, names.join("\n") + "\n");
  console.log("• normalised scripts/icon-names.txt (sorted + deduped)");
}

const axes = "opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200";
const cssUrl =
  `https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:${axes}` +
  `&icon_names=${names.join(",")}&display=block`;

// A modern UA is required or Google serves legacy ttf instead of woff2.
const UA =
  "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

const cssRes = await fetch(cssUrl, { headers: { "User-Agent": UA } });
if (!cssRes.ok) {
  console.error(`Google Fonts CSS request failed: ${cssRes.status}`);
  console.error((await cssRes.text()).slice(0, 400));
  process.exit(1);
}
const css = await cssRes.text();

const fontUrl = css.match(/https:\/\/fonts\.gstatic\.com\/[^)]+/)?.[0];
if (!fontUrl) {
  console.error("No font URL in the returned CSS:\n" + css.slice(0, 400));
  process.exit(1);
}

const fontRes = await fetch(fontUrl);
if (!fontRes.ok) {
  console.error(`Font download failed: ${fontRes.status}`);
  process.exit(1);
}
const buf = Buffer.from(await fontRes.arrayBuffer());

mkdirSync(dirname(OUT_FILE), { recursive: true });
writeFileSync(OUT_FILE, buf);

// Emit the type union from the same list that produced the subset, so the
// `IconName` type and the glyphs in the font can never drift apart.
mkdirSync(dirname(TYPES_FILE), { recursive: true });
writeFileSync(
  TYPES_FILE,
  `// GENERATED by scripts/fetch-icon-font.mjs — do not edit by hand.
// Add the icon name to scripts/icon-names.txt, then run \`npm run fonts:icons\`.
//
// Every name here is guaranteed present in the subsetted woff2, so a typo is a
// TypeScript error rather than a blank box in production.

export const ICON_NAMES = [
${names.map((n) => `  "${n}",`).join("\n")}
] as const;

export type IconName = (typeof ICON_NAMES)[number];
`,
);

console.log(
  `✓ ${names.length} icons → ${OUT_FILE.replace(root + "/", "")} (${(buf.length / 1024).toFixed(1)} KB)`,
);
console.log(`✓ type union → ${TYPES_FILE.replace(root + "/", "")}`);
